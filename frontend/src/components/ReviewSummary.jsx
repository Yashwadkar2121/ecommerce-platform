import { useEffect, useState } from "react";
import { Sparkles, ThumbsUp, ThumbsDown } from "lucide-react";
import { aiService } from "../services/aiService";

// "AI summary of reviews" box. Shows nothing if the product has too few
// reviews or the AI is unavailable - reviews themselves always remain visible.
const ReviewSummary = ({ productId }) => {
  const [state, setState] = useState({ loading: true, summary: null });

  useEffect(() => {
    let active = true;
    setState({ loading: true, summary: null });
    aiService
      .reviewSummary(productId)
      .then(({ data }) => active && setState({ loading: false, summary: data.summary }))
      .catch(() => active && setState({ loading: false, summary: null }));
    return () => {
      active = false;
    };
  }, [productId]);

  if (state.loading) {
    return (
      <div className="mb-6 animate-pulse rounded-xl border border-indigo-100 bg-indigo-50/50 p-5" aria-hidden="true">
        <div className="mb-3 h-4 w-40 rounded bg-indigo-100" />
        <div className="h-3 w-full rounded bg-indigo-100" />
        <div className="mt-2 h-3 w-2/3 rounded bg-indigo-100" />
      </div>
    );
  }
  if (!state.summary) return null;

  const { summary, pros, cons, basedOn } = state.summary;
  return (
    <div className="mb-6 rounded-xl border border-indigo-100 bg-indigo-50/60 p-5">
      <div className="mb-2 flex items-center gap-2 text-sm font-semibold text-indigo-900">
        <Sparkles size={16} /> AI summary of customer reviews
      </div>
      <p className="text-sm text-gray-800">{summary}</p>
      {(pros?.length > 0 || cons?.length > 0) && (
        <div className="mt-3 grid grid-cols-1 gap-3 sm:grid-cols-2">
          {pros?.length > 0 && (
            <ul className="space-y-1 text-sm text-gray-700">
              {pros.map((item) => (
                <li key={item} className="flex items-start gap-2">
                  <ThumbsUp size={14} className="mt-0.5 flex-shrink-0 text-green-600" /> {item}
                </li>
              ))}
            </ul>
          )}
          {cons?.length > 0 && (
            <ul className="space-y-1 text-sm text-gray-700">
              {cons.map((item) => (
                <li key={item} className="flex items-start gap-2">
                  <ThumbsDown size={14} className="mt-0.5 flex-shrink-0 text-red-500" /> {item}
                </li>
              ))}
            </ul>
          )}
        </div>
      )}
      <p className="mt-3 text-xs text-gray-500">
        Generated by AI from {basedOn} reviews. It may contain mistakes.
      </p>
    </div>
  );
};

export default ReviewSummary;
